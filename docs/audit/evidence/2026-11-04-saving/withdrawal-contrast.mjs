import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const root=process.argv[2];
const {GameManager,createMemoryStorage}=await import(pathToFileURL(root+'/public/game/gameManager.js'));
const {PlayerAction}=await import(pathToFileURL(root+'/public/game/gameState.js'));
const {createFakeScheduler}=await import(pathToFileURL(root+'/test/helpers.js'));
const storage=createMemoryStorage();
const game=new GameManager({storage,scheduler:createFakeScheduler()});
game.handleAction(PlayerAction.newGame);
game.handleAction(PlayerAction.pause);
assert.equal(new GameManager({storage,scheduler:createFakeScheduler()}).isSessionSaved,true,'completed control save available');
game.isSessionSaved=false;
assert.equal(new GameManager({storage,scheduler:createFakeScheduler()}).isSessionSaved,false,'successful withdrawal control');
game.handleAction(PlayerAction.resume);
game.handleAction(PlayerAction.moveLeft);
const setItem=storage.setItem;const writes=[];
storage.setItem=(key,value)=>{writes.push([key,value]);if(key==='tetris.savedGameSession'||(key==='tetris.isSessionSaved'&&value==='false'))throw Error('refused');setItem(key,value);};
game.handleAction(PlayerAction.pause);
const observer=new GameManager({storage,scheduler:createFakeScheduler()});
console.log(JSON.stringify({availableAfterFailedSave:observer.isSessionSaved,writerAvailable:game.isSessionSaved,writes:writes.map(([key,value])=>({key,flag:key==='tetris.isSessionSaved'?value:'record-attempt'}))}));
assert.equal(observer.isSessionSaved,false,'a successful withdrawal is not undone by a failed later save');
